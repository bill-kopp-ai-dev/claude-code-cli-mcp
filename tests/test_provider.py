def test_all_tools_tolerate_empty_args():
    """Every tool's signature must accept args={}.

    After the refactor that makes `req` optional (XxxRequestIn | None = None),
    the schema generated by FastMCP no longer requires `req`. We verify the
    signature here — NOT by calling the function, because many tools spawn
    CLI subprocesses or do real I/O that would hang in a unit test.

    The runtime behavior is validated end-to-end by test_mcp_apps/full_probe.py.
    """
    import inspect
    from claude_code_mcp.server import mcp

    tools_dict = {}
    if hasattr(mcp, "_local_provider") and hasattr(mcp._local_provider, "_components"):
        tools_dict = {
            v.name: v
            for k, v in mcp._local_provider._components.items()
            if k.startswith("tool:")
        }
    else:
        tool_manager = getattr(mcp, "_tool_manager", None) or getattr(mcp, "_tools", None)
        if tool_manager is None:
            raise RuntimeError("Cannot access FastMCP tool manager")
        if hasattr(tool_manager, "_tools"):
            tools_dict = tool_manager._tools
        else:
            raise RuntimeError(f"Unsupported tool manager: {type(tool_manager)}")

    assert tools_dict, "No tools registered — FastMCP API may have changed"

    for name, tool in sorted(tools_dict.items()):
        fn = getattr(tool, "fn", tool)
        sig = inspect.signature(fn)
        params = sig.parameters
        if "req" not in params:
            pytest.fail(f"{name}: missing 'req' parameter")
        req_param = params["req"]
        if req_param.default is inspect.Parameter.empty:
            pytest.fail(
                f"{name}: 'req' has no default — caller of args={{}} would hit TypeError. "
                f"Change signature to `req: XxxRequestIn | None = None`."
            )
        ann = str(req_param.annotation)
        if "None" not in ann and "Optional" not in ann:
            pytest.fail(
                f"{name}: 'req' annotation {ann!r} does not include None — "
                f"type checker would reject `req=None`."
            )


def test_allowed_root_slash_grants_full_access():
    """Regression: when allowed_roots contains '/', ANY workspace_path must be allowed.

    The previous check `str(p).startswith(str(root) + '/')` produced '//' for root='/',
    which never matched any real path. This test guards against that regression.
    """
    from pathlib import Path
    from claude_code_mcp.settings import Settings

    s = Settings(allowed_roots=[Path("/")])
    allowed = s.resolved_allowed_roots()
    test_paths = [
        "/home/bill/Codes/zero_trust_env",
        "/etc/passwd",
        "/tmp/test",
        "/home/bill/.ssh/id_rsa",
        "/",
    ]
    for p_str in test_paths:
        p = Path(p_str).expanduser().resolve()
        ok = any(
            str(root) == "/" or p == root or str(p).startswith(str(root) + "/")
            for root in allowed
        )
        assert ok, f"{p_str} should be allowed when allowed_roots=['/'], got rejected"


def test_allowed_root_specific_dir_rejects_others():
    """Specific allowed_roots still rejects paths outside them (sanity check)."""
    from pathlib import Path
    from claude_code_mcp.settings import Settings

    s = Settings(allowed_roots=[Path("/home/bill/Codes/CLI-router-project")])
    allowed = s.resolved_allowed_roots()
    cases = [
        ("/home/bill/Codes/zero_trust_env", False),
        ("/home/bill/Codes/CLI-router-project", True),
        ("/home/bill/Codes/CLI-router-project/subdir", True),
        ("/etc/passwd", False),
    ]
    for p_str, expected in cases:
        p = Path(p_str).expanduser().resolve()
        ok = any(
            str(root) == "/" or p == root or str(p).startswith(str(root) + "/")
            for root in allowed
        )
        assert ok == expected, f"{p_str}: expected {expected}, got {ok}"
